"""Regenerates every Seekgram brand asset from one description of the mark.

    python assets/brand/generate.py

Needs Pillow, fontTools and brotli (to read the woff2). Writes:
    assets/brand/seekgram-mark.svg, header-light.svg, header-dark.svg
    assets/app/seekgram-256.png, seekgram.ico (16..256 px)

The SVGs and the rasters are drawn from the same shapes below, so they cannot drift
apart; the wordmark is Sora SemiBold converted to paths, so nothing needs a webfont.
"""

from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.pens.transformPen import TransformPen
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[2]
BRAND = ROOT / "assets" / "brand"
APP = ROOT / "assets" / "app"
FONT = ROOT / "site" / "fonts" / "Sora.woff2"

BLUE = "#3a9fe0"
DEEP = "#1f69a8"
NAVY = "#0f2740"
PAPER = "#e4f6ff"
FOLD = "#8fd3fb"

# The mark on a 1024 grid: a magnifier whose lens holds a paper plane.
LENS = (432, 432)
RIM = 372
GLASS = 276
HANDLE = ((706, 706), (912, 912))
HANDLE_WIDTH = 150
# Placed by eye-weight, not by bounding box: the lens centre sits midway between the
# plane's area centroid and the centre of its smallest enclosing circle.
PLANE = [(211, 437), (591, 285), (505, 609), (369, 493)]
PLANE_FOLD = [(369, 493), (379, 627), (443, 556)]
# Under 32 px the rim and handle are drawn heavier so the lens stays a ring, not a blob.
SMALL_GLASS = 250


def mark_svg_body() -> str:
    (x1, y1), (x2, y2) = HANDLE
    points = lambda shape: " ".join(f"{x},{y}" for x, y in shape)
    return (
        f'<line x1="{x1}" y1="{y1}" x2="{x2}" y2="{y2}" stroke="{DEEP}" stroke-width="{HANDLE_WIDTH}" stroke-linecap="round"/>\n'
        f'  <circle cx="{LENS[0]}" cy="{LENS[1]}" r="{RIM}" fill="{BLUE}"/>\n'
        f'  <circle cx="{LENS[0]}" cy="{LENS[1]}" r="{GLASS}" fill="{NAVY}"/>\n'
        f'  <polygon points="{points(PLANE)}" fill="{PAPER}"/>\n'
        f'  <polygon points="{points(PLANE_FOLD)}" fill="{FOLD}"/>'
    )


def render_mark(size: int) -> Image.Image:
    scale = 8 if size <= 64 else 4
    side = size * scale
    k = side / 1024
    glass = SMALL_GLASS if size < 32 else GLASS
    image = Image.new("RGBA", (side, side), (0, 0, 0, 0))
    draw = ImageDraw.Draw(image)

    def disc(center, radius, fill):
        cx, cy = center
        draw.ellipse([(cx - radius) * k, (cy - radius) * k, (cx + radius) * k, (cy + radius) * k], fill=fill)

    (x1, y1), (x2, y2) = HANDLE
    draw.line([(x1 * k, y1 * k), (x2 * k, y2 * k)], fill=DEEP, width=round(HANDLE_WIDTH * k))
    disc(HANDLE[1], HANDLE_WIDTH / 2, DEEP)
    disc(LENS, RIM, BLUE)
    disc(LENS, glass, NAVY)
    draw.polygon([(x * k, y * k) for x, y in PLANE], fill=PAPER)
    draw.polygon([(x * k, y * k) for x, y in PLANE_FOLD], fill=FOLD)
    return image.resize((size, size), Image.LANCZOS)


def wordmark_path(text: str, size: float, x: float, baseline: float) -> tuple[str, float]:
    font = instantiateVariableFont(TTFont(FONT), {"wght": 600})
    glyphs = font.getGlyphSet()
    cmap = font.getBestCmap()
    k = size / font["head"].unitsPerEm
    parts = []
    for char in text:
        name = cmap[ord(char)]
        pen = SVGPathPen(glyphs, ntos=lambda v: f"{v:.2f}".rstrip("0").rstrip("."))
        glyphs[name].draw(TransformPen(pen, (k, 0, 0, -k, x, baseline)))
        parts.append(pen.getCommands())
        x += glyphs[name].width * k
    return " ".join(parts), x


def header_svg(text_fill: str) -> str:
    height, pad = 184, 8
    mark = height - 2 * pad
    path, right = wordmark_path("Seekgram", 128, pad + mark + 36, 138.72)
    width = round(right + pad)
    return (
        f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {width} {height}" width="{width}" height="{height}">\n'
        f"  <title>Seekgram</title>\n"
        f'  <g transform="translate({pad} {pad}) scale({mark / 1024:.5f})">{mark_svg_body()}</g>\n'
        f'  <path fill="{text_fill}" d="{path}"/>\n'
        f"</svg>\n"
    )


def main() -> None:
    APP.mkdir(parents=True, exist_ok=True)
    (BRAND / "seekgram-mark.svg").write_text(
        '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 1024 1024" width="1024" height="1024">\n'
        "  <!-- Seekgram: a magnifier whose lens holds a paper plane. Flat fills, no outlines,\n"
        "       transparent background. Generated by assets/brand/generate.py; edit the shapes there. -->\n"
        f"  {mark_svg_body()}\n"
        "</svg>\n",
        encoding="utf-8",
        newline="\n",
    )
    (BRAND / "header-light.svg").write_text(header_svg(NAVY), encoding="utf-8", newline="\n")
    (BRAND / "header-dark.svg").write_text(header_svg(PAPER), encoding="utf-8", newline="\n")
    render_mark(256).save(APP / "seekgram-256.png", optimize=True)
    sizes = [256, 128, 64, 48, 40, 32, 24, 20, 16]
    images = [render_mark(size) for size in sizes]
    images[0].save(APP / "seekgram.ico", sizes=[(s, s) for s in sizes], append_images=images[1:])


if __name__ == "__main__":
    main()
